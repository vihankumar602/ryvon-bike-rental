export function matchesDestinationSeason(d, seasonKey) {
  if (!seasonKey || seasonKey === 'all') return true;
  const s = (d.season || '').toLowerCase();
  if (s.includes('year-round') || s.includes('year round')) return true;

  if (seasonKey === 'oct-mar') {
    return s.includes('oct') || s.includes('nov') || s.includes('dec') || s.includes('jan') || s.includes('feb') || s.includes('mar');
  }
  if (seasonKey === 'apr-nov') {
    return s.includes('apr') || s.includes('may') || s.includes('jun') || s.includes('jul') || s.includes('aug') || s.includes('sep') || s.includes('oct') || s.includes('nov');
  }
  if (seasonKey === 'jun-oct') {
    return s.includes('jun') || s.includes('jul') || s.includes('aug') || s.includes('sep') || s.includes('oct');
  }
  if (seasonKey === 'year-round') {
    return s.includes('year-round') || s.includes('year round');
  }
  return true;
}
